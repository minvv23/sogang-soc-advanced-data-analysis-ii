# B2_1: 형제자매 유무 (해당 항목 선택=1, 미선택=0)
#   s1=형/오빠, s2=누나/언니, s3=남동생, s4=여동생, s5=외동
for col in ['B2_1s1', 'B2_1s2', 'B2_1s3', 'B2_1s4', 'B2_1s5']:
    df[col] = df[col].notna().astype(int)

# B2_1s5(외동)은 s1-s4 모두 0일 때와 동치 → 완전 공선, 제거
df = df.drop(columns=['B2_1s5'])

# ═══════════════════════════════════════════════════════════════
# 4. 이진 변수 리코딩 (1=예/2=아니오 → 1/0)
# ═══════════════════════════════════════════════════════════════
# C3_1: 계엄 이후 민주주의 수업 경험
# C3_2: 가짜뉴스/허위정보 검증 수업 경험
