    'SEQ',        # 일련번호 (식별자)
    'UID',        # 고유 ID (식별자)
    'A3_7_ETC_1', # A3 "기타" 주관식 텍스트
    'SQ2s1',      # 출생연도 → SQ2s2(만나이)와 완전 중복
