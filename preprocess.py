df['C3_2'] = df['C3_2'].map({1: 1, 2: 0})

# ═══════════════════════════════════════════════════════════════
# 5. 내신 등급 역코딩 (높을수록 우수하게)
#    원래: 1등급=최상 ~ 9등급=최하 (낮을수록 우수)
#    변환: 10 - x → 1=최하 ~ 9=최상 (높을수록 우수)
# ═══════════════════════════════════════════════════════════════
for col in ['A6_1', 'A6_2', 'A6_3']:
    df[col] = 10 - df[col]

# ═══════════════════════════════════════════════════════════════
